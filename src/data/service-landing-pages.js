export function getServiceLandingPage(key, language = "es") {
  const page = SERVICE_LANDING_PAGES[key]
  if (!page) throw new Error(`Unknown service landing page: ${key}`)

  const faqWhatsappServiceName = {
    "web-development": { es: "Presencia Esencial", en: "Essential Presence" },
    "custom-software": { es: "Web App Personalizada", en: "Custom Web App" },
    "process-automation": {
      es: "Automatización de Procesos y Sistemas Internos",
      en: "Process Automation and Internal Systems",
    },
    "maintenance-support": { es: "Mantenimiento y Soporte", en: "Maintenance and Support" },
  }[key][language]

  return {
    ...page[language],
    paths: page.paths,
    process: processSteps[language],
    faqWhatsappServiceName,
    faqWhatsappMessage: language === "en"
      ? `Hi, I have another question about the ${faqWhatsappServiceName} service.`
      : `Hola, tengo otra duda respecto al servicio de ${faqWhatsappServiceName}.`,
    relatedServicesTitle: page[language].otherServicesTitle,
    relatedServices: Object.entries(SERVICE_LANDING_PAGES)
      .filter(([relatedKey]) => relatedKey !== key)
      .map(([, relatedPage]) => ({
        title: relatedPage[language].eyebrow,
        description: relatedPage[language].description,
        href: language === "en"
          ? `/en${relatedPage.paths.en.route}/`
          : `${relatedPage.paths.es.route}/`,
      })),
  }
}
